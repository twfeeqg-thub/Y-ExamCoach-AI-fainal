// دالة اختيار رسالة عشوائية حسب السياق
export function getRandomSupportMessage(type: keyof typeof PSYCHOLOGICAL_MESSAGES): SupportMessage {
  const category = PSYCHOLOGICAL_MESSAGES[type];
  if (Array.isArray(category) && category.length > 0) {
    const randomIndex = Math.floor(Math.random() * category.length);
    const item = category[randomIndex];
    if (typeof item === 'string') {
      return { id: 'quote', text: item };
    }
    return item as SupportMessage;
  }
  return {
    id: 'default',
    text: 'نحن معك في كل خطوة نحو بناء تعليم أفضل!',
    subtext: 'حتى لو كنت تبدأ من الصفر.'
  };
}
